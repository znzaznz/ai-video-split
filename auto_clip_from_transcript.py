# Rough estimate for qwen-plus compatible chat (CNY per 1K tokens). Override via env if needed.
RULE_FALLBACK_MAX_CLIPS = 12
DEFAULT_INPUT_CNY_PER_1K = float(__import__("os").environ.get("CLIP_AI_INPUT_CNY_PER_1K", "0.004"))
DEFAULT_OUTPUT_CNY_PER_1K = float(__import__("os").environ.get("CLIP_AI_OUTPUT_CNY_PER_1K", "0.012"))


def estimate_chat_cost_cny(data: dict[str, Any], prompt_text: str, completion_text: str) -> float:
    usage = data.get("usage") or {}
    prompt_tokens = usage.get("prompt_tokens")
    completion_tokens = usage.get("completion_tokens")
    total_tokens = usage.get("total_tokens")

    if prompt_tokens is None or completion_tokens is None:
        # Fallback heuristic when usage is missing.
        if total_tokens is not None:
            pt = int(float(total_tokens) * 0.75)
            ct = max(0, int(float(total_tokens)) - pt)
        else:
            pt = max(1, int(len(prompt_text) / 1.6))
            ct = max(1, int(len(completion_text) / 1.6))
    else:
        pt = int(float(prompt_tokens))
        ct = int(float(completion_tokens))

    return (pt / 1000.0) * DEFAULT_INPUT_CNY_PER_1K + (ct / 1000.0) * DEFAULT_OUTPUT_CNY_PER_1K


def request_json(
    url: str,
    method: str,
    headers: dict[str, str],
    body: dict[str, Any] | None = None,
    timeout: int = 180,
) -> dict[str, Any]:
    data = None
    if body is not None:
        data = json.dumps(body, ensure_ascii=False).encode("utf-8")
    req = urllib.request.Request(url=url, method=method, headers=headers, data=data)
    try:
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            text = resp.read().decode("utf-8")
            return json.loads(text) if text.strip() else {}
    except urllib.error.HTTPError as exc:
        detail = exc.read().decode("utf-8", errors="replace")
        raise RuntimeError(f"HTTP {exc.code} {url}\n{detail}") from exc
    except urllib.error.URLError as exc:
        raise RuntimeError(f"请求失败: {url}\n{exc}") from exc


def get_subprocess_window_kwargs() -> dict[str, Any]:
    if sys.platform != "win32":
        return {}
    return {"creationflags": subprocess.CREATE_NO_WINDOW}


def sanitize_name(name: str) -> str:
    cleaned = re.sub(r"[^\w\-\.\u4e00-\u9fff]+", "_", name.strip())
    cleaned = cleaned.strip("._")
    return cleaned or "clip"


def load_glossary_hint(transcript_json: Path) -> str:
    """Rebuild glossary hint from task title/keywords (no glossary.json on disk)."""
    try:
        from transcript_correct import _glossary_hint_block, build_glossary
    except ImportError:
        return ""

    task_dir = transcript_json.parent
    title = task_dir.name
    user_keywords = ""
    manifest = task_dir / "task_manifest.json"
    if manifest.is_file():
        try:
            data = json.loads(manifest.read_text(encoding="utf-8"))
            title = str(data.get("task_name") or title)
            user_keywords = str(data.get("user_keywords") or "")
        except Exception:
            pass
    hint = _glossary_hint_block(build_glossary(title, user_keywords))
    if not hint or hint == "（无）":
        return ""
    return "转写实体参考（由标题/关键词自动生成，非预置词表）：\n" + hint


def load_sentences(path: Path) -> list[dict[str, Any]]:
    data = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(data, list):
        raise RuntimeError("transcript json 格式错误，期望为句子数组。")
    out: list[dict[str, Any]] = []
    for s in data:
        if not isinstance(s, dict):
            continue
        if "start_ms" not in s or "end_ms" not in s:
            continue
        text = str(s.get("text", "")).strip()
        if not text:
            continue
        out.append(
            {
                "start_ms": int(float(s["start_ms"])),
                "end_ms": int(float(s["end_ms"])),
                "text": text,
            }
        )
    if not out:
        raise RuntimeError("transcript json 中没有可用句子。")
    return out


def build_transcript_for_ai(sentences: list[dict[str, Any]], max_lines: int = 300) -> str:
    # Avoid overlong prompt. Keep earliest content for deterministic behavior.
    lines: list[str] = []
    for i, s in enumerate(sentences[:max_lines], start=1):
        lines.append(f"{i}|{s['start_ms']}|{s['end_ms']}|{s['text']}")
    return "\n".join(lines)


def _looks_like_legacy_full_custom_prompt(text: str) -> bool:
    """Heuristic: older GUI passed the entire user message as custom_user_prompt."""
    t = text.strip()
    if not t:
        return False
    if "输入格式" in t:
        return True
    if "输出必须是 JSON" in t and "要求:" in t:
        return True
    return False


def duration_constraint_text(min_sec: int, max_sec: int) -> str:
    if max_sec > 0:
        return f"每段时长 {min_sec}-{max_sec} 秒"
    return f"每段至少 {min_sec} 秒，不设最长时长上限（按完整主题/观点切，可到数分钟）"


def build_technical_constraints_block(min_sec: int, max_sec: int) -> str:
    dur = duration_constraint_text(min_sec, max_sec)
    return (
        "【技术约束】（必须遵守）\n"
        f"1) {dur}\n"
        "2) 片段互不重叠\n"
        "3) 段数由转写内容与切片目标决定，不设上限，需要几段就输出几段\n"
        "4) 仅返回一个 JSON 对象，不要 markdown；格式："
        '{"clips":[{"title":"短标题","start_ms":0,"end_ms":0,"reason":"短说明"}]}\n'
        "5) title/reason 各不超过 30 字，勿使用英文双引号\n"
    )


def _strip_markdown_json_fence(text: str) -> str:
    t = text.strip()
    if t.startswith("```"):
        t = re.sub(r"^```(?:json)?\s*", "", t, flags=re.I)
        t = re.sub(r"\s*```\s*$", "", t)
    return t.strip()


def _extract_balanced_json(text: str, start: int) -> str | None:
    if start < 0 or start >= len(text):
        return None
    open_ch = text[start]
    close_ch = "}" if open_ch == "{" else "]" if open_ch == "[" else ""
    if not close_ch:
        return None
    depth = 0
    in_str = False
    esc = False
    for i in range(start, len(text)):
        ch = text[i]
        if in_str:
            if esc:
                esc = False
            elif ch == "\\":
                esc = True
            elif ch == '"':
                in_str = False
            continue
        if ch == '"':
            in_str = True
            continue
        if ch == open_ch:
            depth += 1
        elif ch == close_ch:
            depth -= 1
            if depth == 0:
                return text[start : i + 1]
    return None


def _clips_from_parsed_json(data: Any) -> list[dict[str, Any]]:
    if isinstance(data, dict):
        arr = data.get("clips")
        if arr is None:
            for v in data.values():
                if isinstance(v, list):
                    arr = v
                    break
        data = arr
    if not isinstance(data, list):
        raise ValueError("根节点不是 clips 数组。")
    clips: list[dict[str, Any]] = []
    for it in data:
        if not isinstance(it, dict):
            continue
        try:
            start_ms = int(float(it.get("start_ms")))
            end_ms = int(float(it.get("end_ms")))
        except Exception:
            continue
        title = str(it.get("title", "")).strip() or "片段"
        reason = str(it.get("reason", "")).strip()
        if end_ms <= start_ms:
            continue
        clips.append(
            {
                "title": title,
                "start_ms": start_ms,
                "end_ms": end_ms,
                "reason": reason,
            }
        )
    return clips


def _clips_from_loose_regex(content: str) -> list[dict[str, Any]]:
    """Fallback when JSON is broken (e.g. unescaped quotes in reason)."""
    clips: list[dict[str, Any]] = []
    seen: set[tuple[int, int]] = set()
    patterns = [
        re.compile(
            r'"title"\s*:\s*"([^"]{0,80})"\s*,\s*"start_ms"\s*:\s*(\d+)\s*,\s*"end_ms"\s*:\s*(\d+)',
            re.S,
        ),
        re.compile(
            r'"start_ms"\s*:\s*(\d+)\s*,\s*"end_ms"\s*:\s*(\d+)',
            re.S,
        ),
    ]
    for pat in patterns:
        for m in pat.finditer(content):
            if len(m.groups()) == 3:
                title, start_ms, end_ms = m.group(1), int(m.group(2)), int(m.group(3))
            else:
                title, start_ms, end_ms = "片段", int(m.group(1)), int(m.group(2))
            key = (start_ms, end_ms)
            if key in seen or end_ms <= start_ms:
                continue
            seen.add(key)
            clips.append(
                {
                    "title": title.strip() or "片段",
                    "start_ms": start_ms,
                    "end_ms": end_ms,
                    "reason": "",
                }
            )
    return clips


def parse_ai_clips_content(content: str) -> list[dict[str, Any]]:
    text = _strip_markdown_json_fence(content)
    errors: list[str] = []

    for start_ch in ("{", "["):
        pos = text.find(start_ch)
        if pos < 0:
            continue
        chunk = _extract_balanced_json(text, pos)
        if not chunk:
            continue
        try:
            parsed = json.loads(chunk)
            clips = _clips_from_parsed_json(parsed)
            if clips:
                return clips
            errors.append(f"{start_ch} 解析成功但无有效片段")
        except Exception as exc:
            errors.append(f"{start_ch} json.loads: {exc}")

    loose = _clips_from_loose_regex(text)
    if loose:
        return loose

    snippet = text[:240].replace("\n", " ")
    detail = "; ".join(errors[:2]) if errors else "无法识别片段"
    raise ValueError(f"{detail}；响应摘要: {snippet}…")


def build_ai_user_prompt(
    sentences: list[dict[str, Any]],
    min_sec: int,
    max_sec: int,
    slice_goal: str | None,
    slice_logic_how: str | None,
    custom_user_prompt: str | None,
) -> str:
    transcript_block = build_transcript_for_ai(sentences)
    tail = "\n\n输入格式: 行号|start_ms|end_ms|text\n" + transcript_block

    cup = (custom_user_prompt or "").strip()
    if cup and _looks_like_legacy_full_custom_prompt(cup):
        prompt = (
            cup.replace("{max_clips}", "0")
            .replace("{min_sec}", str(min_sec))
            .replace("{max_sec}", str(max_sec))
            .replace("{theme}", "")
        )
        if "输入格式" not in prompt:
            prompt = prompt + tail
        else:
            if transcript_block not in prompt and "行号|" not in prompt:
                prompt = prompt + "\n\n" + transcript_block
        return prompt

    parts: list[str] = [
        "你是视频切片助手。根据逐句时间戳转写，为用户裁剪视频时间段。",
    ]
    goal = (slice_goal or "").strip()
    if goal:
        parts.append("【切片目标】（最高优先级，必须满足）\n" + goal)
    logic = (slice_logic_how or "").strip()
    if logic:
        parts.append("【切片逻辑】\n" + logic)
    parts.append(build_technical_constraints_block(min_sec, max_sec))
    return "\n\n".join(parts) + tail


def build_ai_user_prompt_with_glossary(
    sentences: list[dict[str, Any]],
    min_sec: int,
    max_sec: int,
    slice_goal: str | None,
    slice_logic_how: str | None,
    custom_user_prompt: str | None,
    transcript_json: Path | None = None,
) -> str:
    prompt = build_ai_user_prompt(
        sentences=sentences,
        min_sec=min_sec,
        max_sec=max_sec,
        slice_goal=slice_goal,
        slice_logic_how=slice_logic_how,
        custom_user_prompt=custom_user_prompt,
    )
    if transcript_json is not None:
        hint = load_glossary_hint(transcript_json)
        if hint:
            prompt = prompt + "\n\n" + hint
    return prompt


def split_sentences_by_window(sentences: list[dict[str, Any]], window_ms: int) -> list[list[dict[str, Any]]]:
    if window_ms <= 0:
        return [sentences]
    buckets: dict[int, list[dict[str, Any]]] = {}
    for s in sentences:
        idx = max(0, int(s["start_ms"]) // window_ms)
        buckets.setdefault(idx, []).append(s)
    return [buckets[k] for k in sorted(buckets.keys()) if buckets[k]]


def plan_with_ai(
    api_key: str,
    sentences: list[dict[str, Any]],
    min_sec: int,
    max_sec: int,
    slice_goal: str | None = None,
    slice_logic_how: str | None = None,
    custom_user_prompt: str | None = None,
    transcript_json: Path | None = None,
) -> tuple[list[dict[str, Any]], float]:
    prompt = build_ai_user_prompt_with_glossary(
        sentences=sentences,
        min_sec=min_sec,
        max_sec=max_sec,
        slice_goal=slice_goal,
        slice_logic_how=slice_logic_how,
        custom_user_prompt=custom_user_prompt,
        transcript_json=transcript_json,
    )

    url = "https://dashscope.aliyuncs.com/compatible-mode/v1/chat/completions"
    headers = {
        "Authorization": f"Bearer {api_key}",
        "Content-Type": "application/json",
    }
    body: dict[str, Any] = {
        "model": "qwen-plus",
        "messages": [
            {
                "role": "system",
                "content": (
                    "你只输出一个合法 JSON 对象，格式为 "
                    '{"clips":[{"title":"...","start_ms":0,"end_ms":0,"reason":"..."}]}，'
                    "不要 markdown，不要多余说明。"
                ),
            },
            {"role": "user", "content": prompt},
        ],
        "temperature": 0.2,
        "response_format": {"type": "json_object"},
    }
    try:
        data = request_json(url, "POST", headers, body)
    except RuntimeError as exc:
        if "response_format" not in str(exc) and "json_object" not in str(exc):
            raise
        body.pop("response_format", None)
        data = request_json(url, "POST", headers, body)

    content = (
        ((data.get("choices") or [{}])[0].get("message") or {}).get("content") or ""
    ).strip()
    if not content:
        raise RuntimeError("AI 未返回可用内容。")

    cost_cny = estimate_chat_cost_cny(data, prompt, content)
    clips = parse_ai_clips_content(content)
    if not clips:
        raise RuntimeError("AI 未返回有效片段。")
    return clips, cost_cny


def plan_with_ai_in_chunks(
    api_key: str,
    sentences: list[dict[str, Any]],
    min_sec: int,
    max_sec: int,
    chunk_minutes: int,
    chunk_retries: int,
    rule_fallback_after_retries: bool,
    slice_goal: str | None = None,
    slice_logic_how: str | None = None,
    custom_user_prompt: str | None = None,
    transcript_json: Path | None = None,
) -> tuple[list[dict[str, Any]], float]:
    window_ms = max(1, chunk_minutes) * 60 * 1000
    chunks = split_sentences_by_window(sentences, window_ms)
    if not chunks:
        return [], 0.0

    n = len(chunks)
    all_clips: list[dict[str, Any]] = []
    total_cost = 0.0
    for i, ch in enumerate(chunks, start=1):
        clips: list[dict[str, Any]] = []
        retries = max(0, chunk_retries)
        success = False
        for attempt in range(1, retries + 2):
            try:
                clips, call_cost = plan_with_ai(
                    api_key=api_key,
                    sentences=ch,
                    min_sec=min_sec,
                    max_sec=max_sec,
                    slice_goal=slice_goal,
                    slice_logic_how=slice_logic_how,
                    custom_user_prompt=custom_user_prompt,
                    transcript_json=transcript_json,
                )
                total_cost += float(call_cost)
                print(
                    f"AI 分段选段成功：第{i}/{n}段，第{attempt}次，拿到 {len(clips)} 段，"
                    f"本次估算费用约 ¥{call_cost:.6f}"
                )
                success = True
                break
            except Exception as exc:
                print(f"AI 分段选段失败：第{i}/{n}段，第{attempt}次：{exc}")

        if not success:
            if rule_fallback_after_retries:
                print(f"第{i}/{n}段 AI 重试后仍失败，改规则兜底。")
                clips = plan_with_rules(ch, RULE_FALLBACK_MAX_CLIPS, min_sec, max_sec)
            else:
                print(f"第{i}/{n}段 AI 重试后仍失败，跳过该段（未启用规则兜底）。")
                clips = []
        all_clips.extend(clips)
    return all_clips, total_cost


def plan_with_rules(sentences: list[dict[str, Any]], max_clips: int, min_sec: int, max_sec: int) -> list[dict[str, Any]]:
    clips: list[dict[str, Any]] = []
    i = 0
    n = len(sentences)
    min_ms = min_sec * 1000
    cap_ms = max_sec * 1000 if max_sec > 0 else 0
    punct = "。！？!?；;"
    while i < n and len(clips) < max_clips:
        start = sentences[i]["start_ms"]
        j = i
        last_good = -1
        while j < n:
            end = sentences[j]["end_ms"]
            dur = end - start
            if dur >= min_ms and sentences[j]["text"].rstrip().endswith(tuple(punct)):
                last_good = j
            if cap_ms > 0 and dur > cap_ms:
                break
            j += 1
        if last_good == -1:
            last_good = min(n - 1, j)
        end = sentences[last_good]["end_ms"]
        if end - start >= min_ms:
            text_sample = "".join(x["text"] for x in sentences[i : last_good + 1])[:18]
            clips.append(
                {
                    "title": f"片段{len(clips)+1}_{text_sample}",
                    "start_ms": start,
                    "end_ms": end,
                    "reason": "规则兜底：按时长和句号边界切分",
                }
            )
        i = last_good + 1
    return clips


def normalize_clips(clips: list[dict[str, Any]], video_duration_ms: int, min_sec: int, max_sec: int) -> list[dict[str, Any]]:
    min_ms = min_sec * 1000
    cap_ms = max_sec * 1000 if max_sec > 0 else 0
    out: list[dict[str, Any]] = []
    for c in clips:
        s = max(0, int(c["start_ms"]))
        e = min(video_duration_ms, int(c["end_ms"]))
        if e <= s:
            continue
        if e - s < min_ms:
            e = min(video_duration_ms, s + min_ms)
        if cap_ms > 0 and e - s > cap_ms:
            e = s + cap_ms
        if e <= s:
            continue
        out.append(
            {
                "title": str(c.get("title", "片段")).strip() or "片段",
                "start_ms": s,
                "end_ms": e,
                "reason": str(c.get("reason", "")).strip(),
            }
        )
    # sort and de-overlap
    out.sort(key=lambda x: x["start_ms"])
    merged: list[dict[str, Any]] = []
    last_end = -1
    for c in out:
        if c["start_ms"] < last_end:
            c["start_ms"] = last_end
            if c["end_ms"] <= c["start_ms"]:
                continue
        merged.append(c)
        last_end = c["end_ms"]
    return merged


def probe_duration_ms(video: Path) -> int:
    cmd = [
        "ffprobe",
        "-v",
        "error",
        "-show_entries",
        "format=duration",
        "-of",
        "default=noprint_wrappers=1:nokey=1",
        str(video),
    ]
    try:
        ret = subprocess.run(cmd, check=True, capture_output=True, text=True, **get_subprocess_window_kwargs())
    except FileNotFoundError:
        raise RuntimeError("未找到 ffprobe，请安装 ffmpeg 并加入 PATH。") from None
    except subprocess.CalledProcessError as exc:
        raise RuntimeError(f"ffprobe 执行失败: {exc.stderr}") from None
    try:
        sec = float((ret.stdout or "").strip())
        return int(sec * 1000)
    except Exception:
        raise RuntimeError("无法读取视频时长。") from None


def cut_clips(video: Path, clips: list[dict[str, Any]], out_dir: Path) -> list[dict[str, Any]]:
    clip_dir = out_dir / "clips"
    clip_dir.mkdir(parents=True, exist_ok=True)
    outputs: list[dict[str, Any]] = []
    for idx, c in enumerate(clips, start=1):
        start_sec = c["start_ms"] / 1000.0
        dur_sec = (c["end_ms"] - c["start_ms"]) / 1000.0
        title = sanitize_name(c["title"])
        out_file = clip_dir / f"clip_{idx:02d}_{title}.mp4"
        cmd = [
            "ffmpeg",
            "-y",
            "-ss",
            f"{start_sec:.3f}",
            "-i",
            str(video),
            "-t",
            f"{dur_sec:.3f}",
            "-c:v",
            "libx264",
            "-preset",
            "veryfast",
            "-crf",
            "20",
            "-c:a",
            "aac",
            "-b:a",
            "128k",
            str(out_file),
        ]
        try:
            subprocess.run(cmd, check=True, **get_subprocess_window_kwargs())
        except FileNotFoundError:
            raise RuntimeError("未找到 ffmpeg，请安装并加入 PATH。") from None
        except subprocess.CalledProcessError:
            raise RuntimeError(f"切片失败: {out_file.name}") from None
        outputs.append({**c, "file": str(out_file)})
    return outputs


def run_auto_clip(
    video: Path,
    transcript_json: Path,
    out_dir: Path,
    api_key: str,
    slice_goal: str | None = None,
    slice_logic_how: str | None = None,
    min_sec: int = DEFAULT_MIN_SEC,
    max_sec: int = DEFAULT_MAX_SEC,
    chunk_minutes: int = DEFAULT_CHUNK_MINUTES,
    chunk_retries: int = DEFAULT_CHUNK_RETRIES,
    rule_fallback_after_retries: bool = DEFAULT_RULE_FALLBACK,
    custom_user_prompt: str | None = None,
) -> tuple[list[dict[str, Any]], float]:
    video = video.resolve()
    transcript_json = transcript_json.resolve()
    out_dir = out_dir.resolve()
    out_dir.mkdir(parents=True, exist_ok=True)

    if not video.exists():
        raise RuntimeError(f"视频不存在：{video}")
    if not transcript_json.exists():
        raise RuntimeError(f"转写文件不存在：{transcript_json}")
    if min_sec <= 0:
        raise RuntimeError("min_sec 必须大于 0。")
    if max_sec > 0 and min_sec > max_sec:
        raise RuntimeError("max_sec 小于 min_sec，参数非法。")

    sentences = load_sentences(transcript_json)
    duration_ms = probe_duration_ms(video)

    clips: list[dict[str, Any]] = []
    clip_ai_cost = 0.0
    if api_key.strip():
        clips, clip_ai_cost = plan_with_ai_in_chunks(
            api_key=api_key.strip(),
            sentences=sentences,
            min_sec=min_sec,
            max_sec=max_sec,
            chunk_minutes=chunk_minutes,
            chunk_retries=chunk_retries,
            rule_fallback_after_retries=rule_fallback_after_retries,
            slice_goal=slice_goal,
            slice_logic_how=slice_logic_how,
            custom_user_prompt=custom_user_prompt,
            transcript_json=transcript_json.resolve(),
        )
        print(f"AI 分段选段完成：共 {len(clips)} 段，估算解析(AI)费用约 ¥{clip_ai_cost:.6f}")

    if not clips:
        clips = plan_with_rules(sentences, RULE_FALLBACK_MAX_CLIPS, min_sec, max_sec)
        print(f"AI 未产出有效片段，已改用规则兜底选段：{len(clips)} 段")

    clips = normalize_clips(clips, video_duration_ms=duration_ms, min_sec=min_sec, max_sec=max_sec)
    if not clips:
        raise RuntimeError("没有可切片段。")

    outputs = cut_clips(video, clips, out_dir)
    plan_file = out_dir / "clip_plan.json"
    plan_file.write_text(json.dumps(outputs, ensure_ascii=False, indent=2), encoding="utf-8")

    print(f"视频：{video}")
    print(f"转写：{transcript_json}")
    print(f"输出目录：{out_dir}")
    print(f"片段数：{len(outputs)}")
    print(f"规划文件：{plan_file}")
    for o in outputs:
        print(f"- {o['file']}")
    return outputs, float(clip_ai_cost)


